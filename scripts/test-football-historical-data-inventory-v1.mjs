import assert from 'node:assert/strict';
import { extractRows, deduplicate, temporalCounts } from './audit-football-historical-data-inventory-v1.mjs';

const fixture={fixture:{id:100,date:'2026-08-01T12:00:00Z',status:{short:'FT'}},league:{id:39,season:2026},teams:{home:{id:1,name:'A'},away:{id:2,name:'B'}},score:{fulltime:{home:2,away:1}},goals:{home:2,away:1}};
const doc={schemaVersion:'yang-edge-football-fixtures-captured-v1',capturedAt:'2026-08-01T15:00:00Z',fixtures:[fixture]};
const rows=extractRows(doc,'fixture.json');
assert.equal(rows.length,1);
assert.equal(rows[0].usableForPregameTraining,true);
assert.equal(rows[0].matchId,'soccer-api-football-100');
assert.equal(extractRows({...doc,capturedAt:undefined},'missing.json')[0].usableForPregameTraining,false);
assert.equal(extractRows({...doc,capturedAt:fixture.fixture.date},'early.json')[0].usableForPregameTraining,false);
assert.equal(extractRows({...doc,schemaVersion:'unknown'},'unknown.json')[0].usableForPregameTraining,false);
const penalties=structuredClone(doc);
penalties.fixtures[0].fixture.status.short='PEN';
penalties.fixtures[0].score.fulltime={home:1,away:1};
penalties.fixtures[0].goals={home:5,away:4};
assert.equal(extractRows(penalties,'penalties.json')[0].homeGoals,1);
penalties.fixtures[0].score.fulltime={home:null,away:null};
assert.equal(extractRows(penalties,'no-regulation.json')[0].usableForPregameTraining,false);
assert.equal(deduplicate([...rows,...rows]).length,1);
assert.equal(deduplicate([...rows,...rows])[0].occurrences,2);
assert.equal(deduplicate([...rows,{...rows[0],homeGoals:3}])[0].usableForPregameTraining,false);
assert.equal(deduplicate([...rows,{...rows[0],homeTeam:'fb-team-v1-api-football-3'}])[0].conflict,true);
assert.equal(deduplicate([...rows,{...rows[0],kickoff:'2026-08-01T21:00:00+09:00'}])[0].conflict,false);
const late={...rows[0],resultObservedAt:'2026-08-02T15:00:00Z'};
assert.equal(deduplicate([late,...rows])[0].resultObservedAt,doc.capturedAt);
const unresolved=extractRows({schemaVersion:'ops',games:[{sport:'FOOTBALL',providerFixtureId:100,resultState:'FINAL',providerStatusRaw:'FT',homeScore:2,awayScore:1}]},'ops.json');
assert.equal(unresolved[0].identityQuality,'IDENTITY_UNRESOLVED');
assert.equal(unresolved[0].usableForPregameTraining,false);
assert.equal(deduplicate([...rows,...unresolved])[0].conflict,false);
const target={...rows[0],matchId:'target',kickoff:'2026-09-01T12:00:00Z',resultObservedAt:'2026-09-01T15:00:00Z'};
const sufficient=Array.from({length:30},(_,i)=>({...rows[0],matchId:`past-${i}`}));
assert.equal(temporalCounts([...sufficient,target]).find(r=>r.matchId==='target').passesBaselineSampleGates,true);
const afterCutoff=sufficient.map(r=>({...r,resultObservedAt:target.kickoff}));
assert.equal(temporalCounts([...afterCutoff,target]).find(r=>r.matchId==='target').competitionHistory,0);
const otherLeague=sufficient.map(r=>({...r,league:'other'}));
assert.equal(temporalCounts([...otherLeague,target]).find(r=>r.matchId==='target').competitionHistory,0);
console.log('PASS inventory: observation provenance, regulation vs penalties, unknown schema, exact deduplication, conflicts, no fuzzy identity');
